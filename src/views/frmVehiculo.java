    private void cboMarcaVItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_cboMarcaVItemStateChanged
        // TODO add your handling code here:
        // TODO add your handling code here:
        cboModeloV.removeAllItems();
        int idMarcaSelected = cboMarcaV.getSelectedIndex()+1;
        
        modelos = vehControlador.findModelosByMarca(idMarcaSelected);
        Iterator<Modelo> itr = modelos.iterator();
                
        while(itr.hasNext()){
            Modelo modelo = itr.next();
            cboModeloV.addItem(modelo.getNombreModelo());
        }
    }//GEN-LAST:event_cboMarcaVItemStateChanged

    private void btnGuardarVActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarVActionPerformed
        // TODO add your handling code here:
        if (clienteSeleccionado == null) {
            JOptionPane.showMessageDialog(this, "Primero busque y seleccione un cliente por su DNI", "Cliente no seleccionado", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        String placa = txtPlacaV.getText().trim().toUpperCase();
        String color = txtColorV.getText().trim();
        String anioTexto = txtAnioV.getText().trim();
        
        if (placa.isEmpty()) {
            JOptionPane.showMessageDialog(this, "La placa es obligatoria", "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (cboMarcaV.getSelectedIndex() == -1 || cboModeloV.getSelectedIndex() == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione marca y modelo", "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        Integer anio = null;
        if (!anioTexto.isEmpty()) {
            try {
                anio = Integer.parseInt(anioTexto);
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "El año debe ser un número válido", "Dato inválido", JOptionPane.WARNING_MESSAGE);
                return;
            }
        }
        
        int indiceModelo = cboModeloV.getSelectedIndex();
        if (modelos == null || indiceModelo < 0 || indiceModelo >= modelos.size()) {
            JOptionPane.showMessageDialog(this, "Vuelva a seleccionar el modelo", "Dato inválido", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int idModeloSeleccionado = modelos.get(indiceModelo).getIdModelo();
        
        Vehiculo vehiculo = new Vehiculo();
        vehiculo.setIdPersona(clienteSeleccionado.getIdPersona());
        vehiculo.setPlaca(placa);
        vehiculo.setIdModelo(idModeloSeleccionado);
        vehiculo.setAnio(anio);
        vehiculo.setColor(color.isEmpty() ? null : color);
        
        boolean guardado = vehControlador.registrar(vehiculo);
        
        if (guardado) {
            JOptionPane.showMessageDialog(this, "Vehículo registrado correctamente", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            limpiarFormulario();
            cargarTablaVehiculos();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar el vehiculo. Verifique que la placa no sea repetida", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarVActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String documento = txtClienteV.getText().trim();
        if (documento.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el número de documento del cliente", "Dato requerido", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        Persona persona = personaControlador.buscarPorDocumento(documento);
        if (persona == null) {
            clienteSeleccionado = null;
            JOptionPane.showMessageDialog(this, "No se encontró ningún cliente con ese documento", "Sin resultados", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        clienteSeleccionado = persona;
        JOptionPane.showMessageDialog(this, "Cliente encontrado: " + persona.getNombres() + " " + persona.getApellidos(), "Cliente seleccionado", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEditarVActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarVActionPerformed
        // TODO add your handling code here:
        if (idVehiculoSeleccionado == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un vehículo de la tabla para editar", "Sin selección", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String placa = txtPlacaV.getText().trim();
        String color = txtColorV.getText().trim();
        String anioTexto = txtAnioV.getText().trim();
        if (placa.isEmpty() || cboMarcaV.getSelectedIndex() == -1 || cboModeloV.getSelectedIndex() == -1) {
            JOptionPane.showMessageDialog(this, "Complete placa, marca y modelo", "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        Integer anio = null;
        if (!anioTexto.isEmpty()) {
            try {
                anio = Integer.parseInt(anioTexto);
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "El año debe ser un número válido", "Dato inválido", JOptionPane.WARNING_MESSAGE);
                return;
            }
        }
        int indiceModelo = cboModeloV.getSelectedIndex();
        int idModeloSeleccionado = modelos.get(indiceModelo).getIdModelo();
        
        Vehiculo vehiculo = new Vehiculo();
        vehiculo.setIdVehiculo(idVehiculoSeleccionado);
        vehiculo.setIdModelo(idModeloSeleccionado);
        vehiculo.setPlaca(placa);
        vehiculo.setAnio(anio);
        vehiculo.setColor(color.isEmpty() ? null : color);
        
        boolean actualizado = vehControlador.actualizar(vehiculo);
        if (actualizado) {
            JOptionPane.showMessageDialog(this, "Vehículo actualizado correctamente", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            limpiarFormulario();
            idVehiculoSeleccionado = -1;
            cargarTablaVehiculos();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo actualizar el vehículo", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEditarVActionPerformed

    private void btnEliminarVActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarVActionPerformed
        // TODO add your handling code here:
        if (idVehiculoSeleccionado == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un vehículo de la tabla para eliminar", "Sin selección", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int confirmacion = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar este vehículo?", "Confirmar eliminación", JOptionPane.YES_NO_OPTION, JOptionPane
        .WARNING_MESSAGE);
        if (confirmacion != JOptionPane.YES_OPTION) {
            return;
        }
        boolean eliminado = vehControlador.eliminar(idVehiculoSeleccionado);
        if (eliminado) {
            JOptionPane.showMessageDialog(this, "Vehículo eliminado correctamente", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            limpiarFormulario();
            idVehiculoSeleccionado = -1;
            cargarTablaVehiculos();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo eliminar. Es posible que el vehículo tenga reservas u órdenes de trabajo asociadas", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarVActionPerformed

