    private void btnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIngresarActionPerformed
        // TODO add your handling code here:
        String usuario = txtUsuario.getText().trim();
        String password = utils.Utils.hashearPassword(new String(txtPassword.getPassword()));
        if (usuario.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese usuario y contraseña");
            return;
        }
        
        models.entities.Usuario usuarioAutenticado = controlador.autenticar(usuario, password);

        if (usuarioAutenticado != null) {
           
            Persona p = usuarioAutenticado.getPersona();
            
            // Singleto
            SesionUsuario.getInstancia().iniciar(usuarioAutenticado);
            
            JOptionPane.showMessageDialog(this, "Bienvenido");
            redirigirRol(usuarioAutenticado);
        } else {
            JOptionPane.showMessageDialog(this,
                    "Credenciales invalidas", "Error de acceso",
                    JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnIngresarActionPerformed

