    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        Persona p = new Persona(
            0,
            txtNroDoc.getText(),
            txtNombres.getText(),
            txtApellidos.getText(),
            txtTelefono.getText(),
            txtDireccion.getText(),
            cboSexo.getSelectedItem().toString().charAt(0)
        );

        Usuario u = new Usuario();
        u.setNombreUsuario(txtUsuario.getText());
        u.setPasswordHash(utils.Utils.hashearPassword(new String(txtPassword.getPassword()))); 
        u.setIdRol(1); // rol CLIENTE
        u.setEstado('1');

        boolean ok = usuarioController.registrar(p, u);
        if (ok) {
            JOptionPane.showMessageDialog(this, "Registro exitoso. Ya puedes iniciar sesión.");
            dispose(); // cierra el dialog, vuelve al frmLogin
        } else {
            JOptionPane.showMessageDialog(this, "Error al registrar. Intente nuevamente.",
                "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

