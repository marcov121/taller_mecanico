    private void listadoClientes(){
        DefaultTableModel model = (DefaultTableModel) tblClientes.getModel();
        
        model.setRowCount(0);
        
        List<Persona> clientes = personaControlador.listarClientes();
        for (Persona p : clientes) {
            String sexo = p.getSexo() == 'M' ? "Masculino" : "Femenino";
            String estado = p.getEstado() == '1' ? "Activo" : "Inactivo";
            model.addRow(new Object[]{
                p.getIdPersona(),
                p.getNumeroDocumento(),
                p.getNombres(),
                p.getApellidos(),
                p.getTelefono(),
                p.getDireccion(),
                sexo,
                estado
            });
        }
        tblClientes.setModel(model);
    }
    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        if (clienteActual == null) {
            JOptionPane.showMessageDialog(this, "Primero busque un cliente por su número de documento", "Cliente no seleccionado", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String nombres = txtNombres.getText().trim();
        String apellidos = txtApellidos.getText().trim();
        String telefono = txtTelefono.getText().trim();
        String direccion = txtDireccion.getText().trim();
        if (nombres.isEmpty() || apellidos.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nombres y apellidos son obligatorios", "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Prototype: editar un clon para conservar el original
        Persona editado = clienteActual.clone();
        
        editado.setNombres(nombres);
        editado.setApellidos(apellidos);
        editado.setTelefono(telefono.isEmpty() ? null : telefono);
        editado.setDireccion(direccion);
        editado.setSexo(cboSexo.getSelectedItem().equals("Masculino") ? 'M' : 'F');
        
        boolean actualizado = personaControlador.actualizar(editado);
        
        if (actualizado) {
            clienteActual = editado;
            JOptionPane.showMessageDialog(this, "Datos del cliente actualizado correctamente", "Éxito", JOptionPane.INFORMATION_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo actualizar", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        if (clienteActual == null) {
            JOptionPane.showMessageDialog(this, "Primero busque un cliente por su número de documento", "Cliente no seleccionado", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int confirmacion = JOptionPane.showConfirmDialog(this, "¿Estás seguro de eliminar este cliente?", "Confirmar eliminación", JOptionPane.YES_NO_OPTION);
        if (confirmacion != JOptionPane.YES_OPTION) return;
        boolean eliminacion = personaControlador.eliminar(clienteActual.getIdPersona());
        if (eliminacion) {
            JOptionPane.showMessageDialog(this, "Cliente eliminado correctamente");
            limpiar();
            clienteActual = null;
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo eliminar al cliente", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

