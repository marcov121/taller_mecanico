    void cargarIcono(JButton btn, String ruta){
        // 1. Cargar la imagen del logo
        ImageIcon iconoOriginal = new ImageIcon(getClass().getResource(ruta));

        // 2. Escalar la imagen (Opcional, ajusta 50x50 al tamaño deseado)
        Image imagenEscalada = iconoOriginal.getImage().getScaledInstance(50, 50, Image.SCALE_SMOOTH);
        ImageIcon iconoFinal = new ImageIcon(imagenEscalada);

        // 3. Establecer el icono en el JButton
        btn.setIcon(iconoFinal);
    }
    
