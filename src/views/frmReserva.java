    void cargarVehiculosCliente() {
        cboVehiculo.removeAllItems();
        vehiculosCliente = vehiculoControlador.findVehiculosByPersona(clienteSeleccionado.getIdPersona());
        if (vehiculosCliente.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Este cliente no tiene vehículos registrados", "Sin vehículos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        for (Vehiculo v : vehiculosCliente) {
            cboVehiculo.addItem(v.getPlaca());
        }
    }
    
    void cargarHorariosDisponibles() {
        cboHorario.removeAllItems();
        horariosDisponibles = reservaControlador.listarHorariosDisponibles();
        for (AgendaDisponibilidad a : horariosDisponibles) {
            cboHorario.addItem(a.toString());
        }
    }
    
    void cargarTablaReservas() {
        List<ReservaDetalle> reservas = reservaControlador.listarTodas();
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);
        for (ReservaDetalle r : reservas) {
            modelo.addRow(new Object[] {r.getIdReserva(), r.getClienteNombreCompleto(), r.getPlacaVehiculo(), r.getFechaHorario(), r.getMotivo(), r.getEstado()});
        }
    }
