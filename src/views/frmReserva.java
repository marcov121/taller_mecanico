    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // TODO add your handling code here:
        String documento = txtCliente.getText().trim();
        if (documento.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el número de documento del cliente", "Dato requerido", JOptionPane.WARNING_MESSAGE);
            return;
        }
        Persona persona = personaControlador.buscarPorDocumento(documento);
        if (persona == null) {
            clienteSeleccionado = null;
            cboVehiculo.removeAllItems();
            JOptionPane.showMessageDialog(this, "No se encontró ningún cliente con ese documento", "Sin resultados", JOptionPane.WARNING_MESSAGE);
            return;
        }
        clienteSeleccionado = persona;
        cargarVehiculosCliente();
        cargarHorariosDisponibles();
        JOptionPane.showMessageDialog(this, "Cliente encontrado: " + persona.getNombres() + " " + persona.getApellidos(),
                "Cliente seleccionado", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        if (clienteSeleccionado == null) {
            JOptionPane.showMessageDialog(this, "Primero busque y seleccione un cliente por su DNI", "Cliente no seleccionado", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (cboVehiculo.getSelectedIndex() == -1) {
            JOptionPane.showMessageDialog(this, "Este cliente no tiene vehículos registrados o no seleccionó ninguno", "Sin vehículo", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (cboHorario.getSelectedIndex() == -1) {
            JOptionPane.showMessageDialog(this, "No hay horarios disponibles o no seleccionó ninguno", "Sin horario", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String motivo = txtMotivo.getText().trim();
        if (motivo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "El motivo es obligatorio", "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        Vehiculo vehiculo = vehiculosCliente.get(cboVehiculo.getSelectedIndex());
        AgendaDisponibilidad horario = horariosDisponibles.get(cboHorario.getSelectedIndex());
        
        int idAgendaReal = (horario.getIdAgenda() == -1)
                ? reservaControlador.obtenerOCrearSlot(horario.getFecha(), horario.getHoraInicio(), horario.getHoraFin())
                : horario.getIdAgenda();

        if (idAgendaReal == -1) {
            JOptionPane.showMessageDialog(this, "No se pudo reservar ese horario, intenta con otro", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        Reserva reserva = new Reserva();
        reserva.setIdPersona(clienteSeleccionado.getIdPersona());
        reserva.setIdVehiculo(vehiculo.getIdVehiculo());
        reserva.setIdAgenda(idAgendaReal);
        reserva.setMotivo(motivo);
        
        boolean guardado = reservaControlador.registrar(reserva);
        
        if (guardado) {
            JOptionPane.showMessageDialog(this, "Reserva registrada correctamente", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            txtMotivo.setText("");
            cargarHorariosDisponibles();
            cargarTablaReservas();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar la reserva. Es posible que otro usuario tenga ese horario, vuelve a intentarlo", "Error", JOptionPane.ERROR_MESSAGE);
            cargarHorariosDisponibles();
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnCancelarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelarActionPerformed
        // TODO add your handling code here:
        if (idReservaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione una reserva de la tabla para cancelar", "Sin selección", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int confirmacion = JOptionPane.showConfirmDialog(this, "¿Está seguro de cancelar esta reserva?", "Confirmar cancelación", JOptionPane.YES_NO_OPTION);
        if (confirmacion != JOptionPane.YES_OPTION) return;
        boolean cancelado = reservaControlador.cancelar(idReservaSeleccionada);
        if (cancelado) {
            JOptionPane.showMessageDialog(this, "Reserva cancelada correctamente", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            idReservaSeleccionada = -1;
            cargarTablaReservas();
            cargarHorariosDisponibles();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo cancelar la reserva", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCancelarActionPerformed

    private void btnVolverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVolverActionPerformed
        // TODO add your handling code here:
        javax.swing.JFrame menuDestino;
        if (usuarioSesion == null) {
            menuDestino = new frmMenuPrincipal();
        } else {
            switch (usuarioSesion.getIdRol()) {
                case 1: // CLIENTE
                    menuDestino = new frmMenuCliente(usuarioSesion);
                    break;
                default:
                    menuDestino = new frmMenuPrincipal(usuarioSesion);
                    break;
            }
        }
        menuDestino.setVisible(true);
        menuDestino.setLocationRelativeTo(null);
        this.dispose();
    }//GEN-LAST:event_btnVolverActionPerformed

